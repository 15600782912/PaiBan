// Development-only: freeze Node ICU's Chinese calendar into an offline month table.
// The mini program never depends on Intl or a network service.
const fs=require('node:fs')
const path=require('node:path')
const formatter=new Intl.DateTimeFormat('zh-CN-u-ca-chinese',{timeZone:'UTC',month:'long',day:'numeric'})
const rows=[]
for(let ms=Date.UTC(1999,10,1);ms<=Date.UTC(2101,0,1);ms+=86400000){
  const parts=formatter.formatToParts(new Date(ms))
  if(parts.find(p=>p.type==='day').value==='1') rows.push([ms/86400000,parts.find(p=>p.type==='month').value])
}
const source=`// Generated by tools/generate-lunar.cjs using Node ${process.version}, ICU ${process.versions.icu}.
// UTC day numbers of Chinese lunar month starts; supports Gregorian 2000–2100.
const months=${JSON.stringify(rows)}
const days=['','初一','初二','初三','初四','初五','初六','初七','初八','初九','初十','十一','十二','十三','十四','十五','十六','十七','十八','十九','二十','廿一','廿二','廿三','廿四','廿五','廿六','廿七','廿八','廿九','三十']
function lunarLabel(date) {
  if(!/^\\d{4}-\\d{2}-\\d{2}$/.test(date) || date<'2000-01-01' || date>'2100-12-31') throw new Error('农历日期超出支持范围')
  const stamp=Date.parse(date+'T00:00:00Z')
  if(!Number.isFinite(stamp) || new Date(stamp).toISOString().slice(0,10)!==date) throw new Error('无效日期')
  const day=stamp/86400000
  let lo=0,hi=months.length-1
  while(lo<hi) {
    const mid=Math.ceil((lo+hi)/2)
    if(months[mid][0]<=day) lo=mid
    else hi=mid-1
  }
  const offset=day-months[lo][0]
  return offset===0?months[lo][1]:days[offset+1]
}
module.exports={lunarLabel}
`
fs.writeFileSync(path.join(__dirname,'../miniprogram/utils/lunar.js'),source)
